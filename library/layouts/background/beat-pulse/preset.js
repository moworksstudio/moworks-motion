/* background/beat-pulse: An accent-derived backdrop pulses its glow intensity and saturation on a deterministic, supplied beat grid.
   HyperFrames registry component beat-pulse-background, run as shipped (assets/beat-pulse-background.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (beats, accent, intensity); duration = its mount duration (4 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("background/beat-pulse", {
  params: {"beats": "0.5,1.0,1.5,2.0,2.5,3.0,3.5", "accent": "green", "intensity": "subtle", "duration": 4.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["beats", "accent", "intensity"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "beat-pulse-background.html", p.at, vars, p.duration, p.theme, []);
  },
});
