/* background/starfield: Seek-safe night-sky overlay: sparse or dense stars in three size tiers that twinkle and drift in two parallax layers, radial-masked to keep the frame center clear
   HyperFrames registry block starfield, run as shipped (assets/starfield.html) in an iframe over the target box, scaled from 1920 x 1080 and kept in
   step with the film (ctx.hfFrame + engine/vendor/libs/hf/hf-frame.js). duration = the block's own length (6 s). replace: [[from, to],
   ...] changes copy in the page before it runs (e.g. Vietnamese text). Generated by engine/tests/hf_blocks.py. */
AIMK.preset("background/starfield", {
  params: {"density": "sparse", "tone": "warm", "speed": "slow", "duration": 6.0, "replace": []},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["density", "tone", "speed"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hfFrame(slot, "starfield.html", p.at, p.duration, Object.assign({"size": [1920, 1080], "libs": {}, "urls": {}, "files": [], "dirs": [], "imageVars": []}, { replace: p.replace, images: p.images, vars }));
  },
});
