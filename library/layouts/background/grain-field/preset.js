/* background/grain-field: A clearly visible accent-tinted dot field drifts over a subtle luminance gradient in an exact ambient loop.
   HyperFrames registry component grain-field, run as shipped (assets/grain-field.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (density, accent); duration = its mount duration (4 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("background/grain-field", {
  params: {"density": "fine", "accent": "green", "duration": 4.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["density", "accent"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "grain-field.html", p.at, vars, p.duration, p.theme, []);
  },
});
