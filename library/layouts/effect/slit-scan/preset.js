/* effect/slit-scan: The frame's rows sample an authored subject at offset times: a canvas painter draws row slices of one pure position function evaluated at t minus offset(row), smearing arrival through time until the offsets collapse to zero and the mark holds coherent.
   HyperFrames registry component slit-scan-reveal, run as shipped (assets/slit-scan-reveal.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (axis, spread, resolve_at, accent, exit); duration = its mount duration (4 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("effect/slit-scan", {
  params: {"axis": "rows", "spread": 0.45, "resolve_at": 2.2, "accent": "green", "exit": "none", "duration": 4.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["axis", "spread", "resolve_at", "accent", "exit"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "slit-scan-reveal.html", p.at, vars, p.duration, p.theme, []);
  },
});
