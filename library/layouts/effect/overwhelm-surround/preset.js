/* effect/overwhelm-surround: Tasks, tabs, pings, and notification bubbles accelerate inward around a calm central subject, turning overload into visible spatial pressure.
   HyperFrames registry component overwhelm-surround, run as shipped (assets/overwhelm-surround.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (count, centerLabel, intensity); duration = its mount duration (4.5 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("effect/overwhelm-surround", {
  params: {"count": 16, "centerLabel": "You", "intensity": 1, "duration": 4.5, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["count", "centerLabel", "intensity"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "overwhelm-surround.html", p.at, vars, p.duration, p.theme, []);
  },
});
