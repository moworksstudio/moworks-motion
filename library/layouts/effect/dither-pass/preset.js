/* effect/dither-pass: Bayer-matrix ordered dithering quantizes a slotted scene (rasterized once at mount): the image emerges from pure 2-tone noise to clean, or dissolves the reverse. Stateless per frame, never error diffusion.
   HyperFrames registry component ordered-dither-pass, run as shipped (assets/ordered-dither-pass.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (matrix, direction, levels, accent, exit); duration = its mount duration (3.5 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("effect/dither-pass", {
  params: {"matrix": "4", "direction": "in", "levels": 2, "accent": "green", "exit": "none", "duration": 3.5, "theme": {}, "slots": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["matrix", "direction", "levels", "accent", "exit"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "ordered-dither-pass.html", p.at, vars, p.duration, p.theme, [], p.slots);
  },
});
