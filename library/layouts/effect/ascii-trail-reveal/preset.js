/* effect/ascii-trail-reveal: An authored S-curve sweeps through a deterministic ASCII grid, flipping cells away to reveal a labeled panel.
   HyperFrames registry component ascii-trail-reveal, run as shipped (assets/ascii-trail-reveal.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (label, accent, trail_width); duration = its mount duration (4 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("effect/ascii-trail-reveal", {
  params: {"label": "The reveal", "accent": "green", "trail_width": "narrow", "duration": 4.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["label", "accent", "trail_width"]) if (p[k] !== undefined) vars[k] = p[k];
    ctx.css("effect/ascii-trail-reveal", "[data-composition-id=\"ascii-trail-reveal\"] .atr-grid { background: transparent; }");   // kit-side fix, the row's notes say why
    for (const slot of els) ctx.hf(slot, "ascii-trail-reveal.html", p.at, vars, p.duration, p.theme, []);
  },
});
