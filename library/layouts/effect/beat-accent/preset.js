/* effect/beat-accent: A single music-hit sting: impact flash, micro scale-pulse on the subject, immediate decay.
   HyperFrames registry component beat-accent, run as shipped (assets/beat-accent.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (text, flashColor, intensity); duration = its mount duration (4 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("effect/beat-accent", {
  params: {"text": "BOOM", "flashColor": "accent", "intensity": 1, "duration": 4.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["text", "flashColor", "intensity"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "beat-accent.html", p.at, vars, p.duration, p.theme, []);
  },
});
