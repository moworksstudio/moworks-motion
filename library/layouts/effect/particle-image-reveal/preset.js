/* effect/particle-image-reveal: A seeded deterministic particle field converges and settles while a slotted image reveals beneath it, the trail thinning until the image holds clean.
   HyperFrames registry component particle-image-reveal, run as shipped (assets/particle-image-reveal.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (density, direction, accent, exit); duration = its mount duration (4 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("effect/particle-image-reveal", {
  params: {"density": "med", "direction": "ltr", "accent": "green", "exit": "none", "duration": 4.0, "theme": {}, "slots": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["density", "direction", "accent", "exit"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "particle-image-reveal.html", p.at, vars, p.duration, p.theme, [], p.slots);
  },
});
