/* effect/nucleus-orbit: A fixed center nucleus anchors deterministic satellite orbits that settle into a composed lockup.
   HyperFrames registry component locked-nucleus-orbit, run as shipped (assets/locked-nucleus-orbit.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (label, accent, satellites); duration = its mount duration (4 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("effect/nucleus-orbit", {
  params: {"label": "core", "accent": "green", "satellites": 4, "duration": 4.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["label", "accent", "satellites"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "locked-nucleus-orbit.html", p.at, vars, p.duration, p.theme, []);
  },
});
