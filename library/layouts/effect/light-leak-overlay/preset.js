/* effect/light-leak-overlay: Finite CSS light-leak overlay for memory beats and motivated transitions
   HyperFrames registry block organic-light-leak-overlay, run as shipped (assets/organic-light-leak-overlay.html) in an iframe over the target box, scaled from 1920 x 1080 and kept in
   step with the film (ctx.hfFrame + engine/vendor/libs/hf/hf-frame.js). duration = the block's own length (4 s). replace: [[from, to],
   ...] changes copy in the page before it runs (e.g. Vietnamese text). Generated by engine/tests/hf_blocks.py. */
AIMK.preset("effect/light-leak-overlay", {
  params: {"duration": 4.0, "replace": []},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of []) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hfFrame(slot, "organic-light-leak-overlay.html", p.at, p.duration, Object.assign({"size": [1920, 1080], "libs": {}, "urls": {}, "files": ["demo-backdrop.jpg"], "dirs": [], "imageVars": []}, { replace: p.replace, images: p.images, vars }));
  },
});
