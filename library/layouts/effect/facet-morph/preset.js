/* effect/facet-morph: A faceted low-poly mass of 36 triangles continuously reshapes between three authored silhouettes (blob, mark, badge) with per-facet flat shading that recomputes as the vertices move. Light reads from the upper left; lit facets lift toward a pale accent-tinted tone while turned-away facets fall toward near-black. One calm continuous morph, then a settled hold.
   HyperFrames registry component facet-morph, run as shipped (assets/facet-morph.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (forms, hold_last, accent, exit); duration = its mount duration (5 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("effect/facet-morph", {
  params: {"forms": "blob,mark,badge", "hold_last": true, "accent": "green", "exit": "none", "duration": 5.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["forms", "hold_last", "accent", "exit"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "facet-morph.html", p.at, vars, p.duration, p.theme, []);
  },
});
