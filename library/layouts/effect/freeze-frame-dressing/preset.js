/* effect/freeze-frame-dressing: Timeline-driven paper, tape, and flash dressing for a freeze-frame or background-removed subject
   HyperFrames registry block freeze-frame-dressing, run as shipped (assets/freeze-frame-dressing.html) in an iframe over the target box, scaled from 1920 x 1080 and kept in
   step with the film (ctx.hfFrame + engine/vendor/libs/hf/hf-frame.js). duration = the block's own length (4 s). replace: [[from, to],
   ...] changes copy in the page before it runs (e.g. Vietnamese text). Generated by engine/tests/hf_blocks.py. */
AIMK.preset("effect/freeze-frame-dressing", {
  params: {"duration": 4.0, "replace": []},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of []) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hfFrame(slot, "freeze-frame-dressing.html", p.at, p.duration, Object.assign({"size": [1920, 1080], "libs": {}, "urls": {}, "files": ["demo-background.jpg", "demo-cutout.webp"], "dirs": [], "imageVars": []}, { replace: p.replace, images: p.images, vars }));
  },
});
