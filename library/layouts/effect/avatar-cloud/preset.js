/* effect/avatar-cloud: Lettermark avatars populate a loose elliptical cloud while fine SVG links draw between the community and its central proof label.
   HyperFrames registry component avatar-cloud, run as shipped (assets/avatar-cloud.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (avatarCount, showLinks, label); duration = its mount duration (5 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("effect/avatar-cloud", {
  params: {"avatarCount": 10, "showLinks": "yes", "label": "50k builders", "duration": 5.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["avatarCount", "showLinks", "label"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "avatar-cloud.html", p.at, vars, p.duration, p.theme, []);
  },
});
