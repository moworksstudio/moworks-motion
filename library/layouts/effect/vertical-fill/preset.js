/* effect/vertical-fill: Portrait media filling a widescreen frame via blurred-scale, mirror, or copy side fills; grid texture and foreground contrast lift (images inside the block; keep live footage in the host)
   HyperFrames registry block yt-vertical-fill, run as shipped (assets/yt-vertical-fill.html) in an iframe over the target box, scaled from 1920 x 1080 and kept in
   step with the film (ctx.hfFrame + engine/vendor/libs/hf/hf-frame.js). duration = the block's own length (8 s). replace: [[from, to],
   ...] changes copy in the page before it runs (e.g. Vietnamese text). Generated by engine/tests/hf_blocks.py. */
AIMK.preset("effect/vertical-fill", {
  params: {"duration": 8.0, "replace": []},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of []) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hfFrame(slot, "yt-vertical-fill.html", p.at, p.duration, Object.assign({"size": [1920, 1080], "libs": {}, "urls": {}, "files": [], "dirs": [], "imageVars": []}, { replace: p.replace, images: p.images, vars }));
  },
});
