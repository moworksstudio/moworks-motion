/* hand/path-text: Handwriting flowing along any SVG path with a per-character reveal; the path is the only geometry input
   HyperFrames registry block hw-path-text, run as shipped (assets/hw-path-text.html) in an iframe over the target box, scaled from 1920 x 1080 and kept in
   step with the film (ctx.hfFrame + engine/vendor/libs/hf/hf-frame.js). duration = the block's own length (6 s). replace: [[from, to],
   ...] changes copy in the page before it runs (e.g. Vietnamese text). Generated by engine/tests/hf_blocks.py. */
AIMK.preset("hand/path-text", {
  params: {"duration": 6.0, "replace": []},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of []) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hfFrame(slot, "hw-path-text.html", p.at, p.duration, Object.assign({"size": [1920, 1080], "libs": {}, "urls": {}, "files": [], "dirs": ["assets"], "imageVars": []}, { replace: p.replace, images: p.images, vars }));
  },
});
