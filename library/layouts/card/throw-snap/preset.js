/* card/throw-snap: A five-shot rail whips past on a fast decaying curve, then overshoots and snaps the selected hero shot exactly to center.
   HyperFrames registry component velocity-throw-snap, run as shipped (assets/velocity-throw-snap.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (hero_index, accent, card_label_prefix); duration = its mount duration (4 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("card/throw-snap", {
  params: {"hero_index": 2, "accent": "green", "card_label_prefix": "Shot", "duration": 4.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["hero_index", "accent", "card_label_prefix"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "velocity-throw-snap.html", p.at, vars, p.duration, p.theme, []);
  },
});
