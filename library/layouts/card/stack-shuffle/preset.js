/* card/stack-shuffle: A stack of 3 to 5 slotted cards reshuffles on cues: the back card throws over the top and lands at the front with real mass, the rest compress and resettle; cues that land mid-flight redirect the moving cards with velocity preserved.
   HyperFrames registry component spring-stack-shuffle, run as shipped (assets/spring-stack-shuffle.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (cards, cues, accent, exit); duration = its mount duration (4 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("card/stack-shuffle", {
  params: {"cards": 4, "cues": "0.9, 1.7, 1.95", "accent": "green", "exit": "none", "duration": 4.0, "theme": {}, "slots": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["cards", "cues", "accent", "exit"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "spring-stack-shuffle.html", p.at, vars, p.duration, p.theme, [], p.slots);
  },
});
