/* card/stagger-cascade: A responsive grid of tile cards that fades and travels into place with an evenly spaced per-item GSAP stagger. The ordered cascade is the only visual mechanic.
   HyperFrames registry component stagger-cascade, run as shipped (assets/stagger-cascade.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (itemCount, stagger, direction); duration = its mount duration (4 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("card/stagger-cascade", {
  params: {"itemCount": 6, "stagger": 60, "direction": "up", "duration": 4.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["itemCount", "stagger", "direction"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "stagger-cascade.html", p.at, vars, p.duration, p.theme, []);
  },
});
