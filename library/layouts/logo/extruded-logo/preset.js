/* logo/extruded-logo: Beveled 3D letters flip up one by one, the word swings so light runs across the bevels, then settles for a readable hold. Chrome, gold or matte.
   HyperFrames registry block extruded-logo, run as shipped (assets/extruded-logo.html) in an iframe over the target box, scaled from 1920 x 1080 and kept in
   step with the film (ctx.hfFrame + engine/vendor/libs/hf/hf-frame.js). duration = the block's own length (5 s). replace: [[from, to],
   ...] changes copy in the page before it runs (e.g. Vietnamese text). Generated by engine/tests/hf_blocks.py. */
AIMK.preset("logo/extruded-logo", {
  params: {"duration": 5.0, "replace": []},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of []) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hfFrame(slot, "extruded-logo.html", p.at, p.duration, Object.assign({"size": [1920, 1080], "libs": {}, "urls": {}, "files": [], "dirs": ["assets"], "imageVars": []}, { replace: p.replace, images: p.images, vars }));
  },
});
