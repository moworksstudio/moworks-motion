/* cursor/multiplayer: Labeled collaborator cursors with token-derived colors and soft glows drift from spread positions into a shared center zone, proving live multiplayer presence.
   HyperFrames registry component multiplayer-cursors, run as shipped (assets/multiplayer-cursors.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (cursorCount, labels); duration = its mount duration (6 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("cursor/multiplayer", {
  params: {"cursorCount": 4, "labels": "Ana,Ken,Wen,Mia", "duration": 6.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["cursorCount", "labels"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "multiplayer-cursors.html", p.at, vars, p.duration, p.theme, []);
  },
});
