/* cursor/gesture-tap: A contact circle taps a mobile pill button, releases it into a new labeled accent state, and lifts away.
   HyperFrames registry component gesture-tap, run as shipped (assets/gesture-tap.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (tap_label, response_label, accent); duration = its mount duration (3 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("cursor/gesture-tap", {
  params: {"tap_label": "Follow", "response_label": "Following", "accent": "green", "duration": 3.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["tap_label", "response_label", "accent"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "gesture-tap.html", p.at, vars, p.duration, p.theme, []);
  },
});
