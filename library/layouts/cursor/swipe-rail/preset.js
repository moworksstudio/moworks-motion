/* cursor/swipe-rail: A contact circle leads a horizontal card rail through a fast drag, momentum carry, and settled snap to the next card.
   HyperFrames registry component swipe-rail, run as shipped (assets/swipe-rail.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (card_count, accent, card_label_prefix); duration = its mount duration (4 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("cursor/swipe-rail", {
  params: {"card_count": 4, "accent": "green", "card_label_prefix": "Feature", "duration": 4.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["card_count", "accent", "card_label_prefix"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "swipe-rail.html", p.at, vars, p.duration, p.theme, []);
  },
});
