/* cursor/zoom-follow: Screen-recording auto-zoom: the camera pushes in toward each upcoming click, trails the cursor on a smooth spring, marks every click with a press and a ring, then eases back out to the full screen as the cursor leaves.
   HyperFrames registry component cursor-zoom-follow, run as shipped (assets/cursor-zoom-follow.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (image, zoom, click1_x, click1_y, click2_x, click2_y, click3_x, click3_y, accent); duration = its mount duration (5.8 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("cursor/zoom-follow", {
  params: {"image": "", "zoom": 1.8, "click1_x": 68.5, "click1_y": 7.5, "click2_x": 50, "click2_y": 48.5, "click3_x": 90.5, "click3_y": 7.5, "accent": "#0a84ff", "duration": 5.8, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["image", "zoom", "click1_x", "click1_y", "click2_x", "click2_y", "click3_x", "click3_y", "accent"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "cursor-zoom-follow.html", p.at, vars, p.duration, p.theme, []);
  },
});
