/* cursor/glyph-trail: A tutorial cursor path: on a settings screen the arrow clicks through three steps, leaving a dotted trail spaced evenly by distance and a numbered marker at each click; each step's trail fades as the next move begins.
   HyperFrames registry component cursor-glyph-trail, run as shipped (assets/cursor-glyph-trail.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (glyphs, density, path, fade, accent, exit); duration = its mount duration (3.5 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("cursor/glyph-trail", {
  params: {"glyphs": "", "density": "med", "path": "sweep", "fade": 0.5, "accent": "green", "exit": "none", "duration": 3.5, "theme": {}, "slots": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["glyphs", "density", "path", "fade", "accent", "exit"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "cursor-glyph-trail.html", p.at, vars, p.duration, p.theme, [], p.slots);
  },
});
