/* cursor/context-menu: A cursor right-clicks a file, a context menu blooms from its tip, the hover highlight tracks the item under it, and the chosen action plays out: duplicate, rename, move to trash, or a confirmation toast.
   HyperFrames registry component cursor-context-menu, run as shipped (assets/cursor-context-menu.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (items, pick, tone); duration = its mount duration (3.9 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("cursor/context-menu", {
  params: {"items": "Open,Rename,Duplicate,Share,Move to Trash", "pick": 2, "tone": "light", "duration": 3.9, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["items", "pick", "tone"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "cursor-context-menu.html", p.at, vars, p.duration, p.theme, []);
  },
});
