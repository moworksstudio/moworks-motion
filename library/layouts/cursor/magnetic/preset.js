/* cursor/magnetic: A soft dot pointer glides across an editor toolbar, is pulled into each button and morphs into its rounded hover plate while the icon leans toward it, presses one, and leaves as a dot.
   HyperFrames registry component magnetic-cursor, run as shipped (assets/magnetic-cursor.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (accent, tone, visits, press); duration = its mount duration (3.6 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("cursor/magnetic", {
  params: {"accent": "#3b82f6", "tone": "light", "visits": "0,3", "press": 2, "duration": 3.6, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["accent", "tone", "visits", "press"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "magnetic-cursor.html", p.at, vars, p.duration, p.theme, []);
  },
});
