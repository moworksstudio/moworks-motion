/* cursor/oversized: The look-here pointer for a video: the macOS arrow at 3.5x its normal size lands its tip on one control, clicks it on, settles just below it so the result stays in view, then exits off-screen
   HyperFrames registry component oversized-cursor, run as shipped (assets/oversized-cursor.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (cursor_variant, target_x, target_y, click_label, exit); duration = its mount duration (2.6 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("cursor/oversized", {
  params: {"cursor_variant": "light", "target_x": 55, "target_y": 55, "click_label": "Generate", "exit": "none", "duration": 2.6, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["cursor_variant", "target_x", "target_y", "click_label", "exit"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "oversized-cursor.html", p.at, vars, p.duration, p.theme, []);
  },
});
