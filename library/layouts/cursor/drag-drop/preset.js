/* cursor/drag-drop: A cursor grabs a task card, lifts and tilts it into its motion, carries it in lockstep to an empty column, drops it with a small settle, and the list closes the gap behind it.
   HyperFrames registry component cursor-drag-drop, run as shipped (assets/cursor-drag-drop.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (card_label, accent, tone); duration = its mount duration (3.6 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("cursor/drag-drop", {
  params: {"card_label": "Fix checkout validation", "accent": "#0a84ff", "tone": "light", "duration": 3.6, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["card_label", "accent", "tone"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "cursor-drag-drop.html", p.at, vars, p.duration, p.theme, []);
  },
});
