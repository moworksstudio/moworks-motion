/* cursor/annotate: A marker pen glides onto the frame and hand-draws a loose loop, an underline, or an arrow around a region, the ink laid exactly under its nib, then lifts and leaves.
   HyperFrames registry component cursor-annotate, run as shipped (assets/cursor-annotate.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (shape, color, target_x, target_y, target_w, target_h); duration = its mount duration (2.95 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("cursor/annotate", {
  params: {"shape": "circle", "color": "#f43f5e", "target_x": 40, "target_y": 38, "target_w": 20, "target_h": 16, "duration": 2.95, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["shape", "color", "target_x", "target_y", "target_w", "target_h"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "cursor-annotate.html", p.at, vars, p.duration, p.theme, []);
  },
});
