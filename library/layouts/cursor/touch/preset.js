/* cursor/touch: A translucent contact-circle gesture actor for mobile UI scenes: it touches the glass on the frame the host target responds, then lifts. Tap or swipe, picked by variable.
   HyperFrames registry component touch-indicator, run as shipped (assets/touch-indicator.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (gesture, polarity, targetX, targetY); duration = its mount duration (4 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("cursor/touch", {
  params: {"gesture": "tap", "polarity": "light", "targetX": 50, "targetY": 55, "duration": 4.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["gesture", "polarity", "targetX", "targetY"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "touch-indicator.html", p.at, vars, p.duration, p.theme, []);
  },
});
