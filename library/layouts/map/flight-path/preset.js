/* map/flight-path: Apple-style realistic map animation with a plane flying from New York to Paris, marker circle, landing pop, and sound effects.
   HyperFrames registry block nyc-paris-flight, run as shipped (assets/nyc-paris-flight.html) in an iframe over the target box, scaled from 1920 x 1080 and kept in
   step with the film (ctx.hfFrame + engine/vendor/libs/hf/hf-frame.js). duration = the block's own length (6 s). replace: [[from, to],
   ...] changes copy in the page before it runs (e.g. Vietnamese text). Generated by engine/tests/hf_blocks.py. */
AIMK.preset("map/flight-path", {
  params: {"duration": 6.0, "replace": []},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of []) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hfFrame(slot, "nyc-paris-flight.html", p.at, p.duration, Object.assign({"size": [1920, 1080], "libs": {}, "urls": {}, "files": [], "dirs": ["assets"], "imageVars": []}, { replace: p.replace, images: p.images, vars }));
  },
});
