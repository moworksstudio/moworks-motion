/* motion/spring-pop: A badge pops in from a visible near-rest scale, overshoots full size once, and settles cleanly.
   HyperFrames registry component spring-pop, run as shipped (assets/spring-pop.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (overshoot, fromScale, text); duration = its mount duration (2 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("motion/spring-pop", {
  params: {"overshoot": 1.7, "fromScale": 0.9, "text": "New", "duration": 2.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["overshoot", "fromScale", "text"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "spring-pop.html", p.at, vars, p.duration, p.theme, []);
  },
});
