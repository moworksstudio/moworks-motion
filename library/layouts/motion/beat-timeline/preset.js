/* motion/beat-timeline: A paused master-timeline orchestration spine that pins titled beat rows to evenly spaced named labels. Each row enters on its label, holds with the sequence, then exits with the group.
   HyperFrames registry component beat-timeline, run as shipped (assets/beat-timeline.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (beatCount, interval, labels); duration = its mount duration (5.5 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("motion/beat-timeline", {
  params: {"beatCount": 4, "interval": 0.6, "labels": "One,Two,Three,Four", "duration": 5.5, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["beatCount", "interval", "labels"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "beat-timeline.html", p.at, vars, p.duration, p.theme, []);
  },
});
