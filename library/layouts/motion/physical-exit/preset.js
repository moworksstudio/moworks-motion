/* motion/physical-exit: A card exits with physical momentum in toss, drop, or slide mode, carrying acceleration and rotation through the final offscreen pose without fading.
   HyperFrames registry component physical-exit, run as shipped (assets/physical-exit.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (mode, text, accent); duration = its mount duration (3 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("motion/physical-exit", {
  params: {"mode": "toss", "text": "Later", "accent": "green", "duration": 3.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["mode", "text", "accent"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "physical-exit.html", p.at, vars, p.duration, p.theme, []);
  },
});
