/* motion/echo-trail: A moving element renders with N ghosted copies of itself at t minus i times delta, opacity stepped down per ghost; one traversal, echoes collapsing into the settled element at rest.
   HyperFrames registry component echo-trail, run as shipped (assets/echo-trail.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (echoes, delta, path, accent, exit); duration = its mount duration (3.5 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("motion/echo-trail", {
  params: {"echoes": 4, "delta": 0.09, "path": "sweep", "accent": "green", "exit": "none", "duration": 3.5, "theme": {}, "slots": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["echoes", "delta", "path", "accent", "exit"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "echo-trail.html", p.at, vars, p.duration, p.theme, [], p.slots);
  },
});
