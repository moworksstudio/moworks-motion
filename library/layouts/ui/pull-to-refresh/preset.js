/* ui/pull-to-refresh: A mobile list pulls through nonlinear rubber-band resistance, arms at a threshold, commits to a bounded loading indicator, then snaps exactly back to rest.
   HyperFrames registry component pull-to-refresh, run as shipped (assets/pull-to-refresh.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (pullDistance, spinnerStyle); duration = its mount duration (4 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("ui/pull-to-refresh", {
  params: {"pullDistance": 120, "spinnerStyle": "ring", "duration": 4.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["pullDistance", "spinnerStyle"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "pull-to-refresh.html", p.at, vars, p.duration, p.theme, []);
  },
});
