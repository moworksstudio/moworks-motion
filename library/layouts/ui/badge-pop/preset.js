/* ui/badge-pop: A transitions.dev-inspired notification badge pop with elastic scale and count reveal
   HyperFrames registry component badge-pop, run as shipped (assets/demo.html) in an iframe over the target box, scaled from 1920 x 1080 and kept in
   step with the film (ctx.hfFrame + engine/vendor/libs/hf/hf-frame.js). duration = the block's own length (5 s). replace: [[from, to],
   ...] changes copy in the page before it runs (e.g. Vietnamese text). Generated by engine/tests/hf_blocks.py. */
AIMK.preset("ui/badge-pop", {
  params: {"count": "3", "accent": "red", "surface": "light", "duration": 5.0, "replace": []},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["count", "accent", "surface"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hfFrame(slot, "demo.html", p.at, p.duration, Object.assign({"size": [1920, 1080], "libs": {}, "urls": {}, "files": ["badge-pop.html"], "dirs": [], "imageVars": []}, { replace: p.replace, images: p.images, vars }));
  },
});
