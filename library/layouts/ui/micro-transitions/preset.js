/* ui/micro-transitions: A transitions.dev-inspired pack of badge, dropdown, modal, tabs, tooltip, and success-check micro transitions
   HyperFrames registry component micro-transitions, run as shipped (assets/demo.html) in an iframe over the target box, scaled from 1920 x 1080 and kept in
   step with the film (ctx.hfFrame + engine/vendor/libs/hf/hf-frame.js). duration = the block's own length (5 s). replace: [[from, to],
   ...] changes copy in the page before it runs (e.g. Vietnamese text). Generated by engine/tests/hf_blocks.py. */
AIMK.preset("ui/micro-transitions", {
  params: {"badge": "3", "tooltip": "Copied", "tone": "red", "travel": "standard", "duration": 5.0, "replace": []},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["badge", "tooltip", "tone", "travel"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hfFrame(slot, "demo.html", p.at, p.duration, Object.assign({"size": [1920, 1080], "libs": {}, "urls": {}, "files": ["micro-transitions.html"], "dirs": [], "imageVars": []}, { replace: p.replace, images: p.images, vars }));
  },
});
