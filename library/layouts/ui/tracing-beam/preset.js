/* ui/tracing-beam: A glowing dash follows one SVG path through three UI elements, lifting and brightening each element in sequence.
   HyperFrames registry component tracing-beam, run as shipped (assets/tracing-beam.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (labels, accent); duration = its mount duration (4.5 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("ui/tracing-beam", {
  params: {"labels": "Search,Preview,Export", "accent": "cyan", "duration": 4.5, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["labels", "accent"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "tracing-beam.html", p.at, vars, p.duration, p.theme, []);
  },
});
