/* ui/focus-swap: Moves attention between two side-by-side cards as one recedes with scale, blur, and dimming while the other advances to full focus.
   HyperFrames registry component focus-swap, run as shipped (assets/focus-swap.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (focus, blurPx, dim); duration = its mount duration (1.5 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("ui/focus-swap", {
  params: {"focus": "b", "blurPx": 6, "dim": 0.5, "duration": 1.5, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["focus", "blurPx", "dim"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "focus-swap.html", p.at, vars, p.duration, p.theme, []);
  },
});
