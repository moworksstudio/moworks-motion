/* ui/scroll-feed: A loop-friendly column of varied skeleton post cards scrolls upward with subtle motion trails and an agitated pace.
   HyperFrames registry component scroll-feed, run as shipped (assets/scroll-feed.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (speed, card_count, cues, exit); duration = its mount duration (4 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("ui/scroll-feed", {
  params: {"speed": "doom", "card_count": 6, "cues": "", "exit": "none", "duration": 4.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["speed", "card_count", "cues", "exit"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "scroll-feed.html", p.at, vars, p.duration, p.theme, []);
  },
});
