/* ui/icon-morph-beat: An icon morphs between authored state silhouettes, shifts to an accent color, and marks completion with one restrained pulse.
   HyperFrames registry component icon-morph-beat, run as shipped (assets/icon-morph-beat.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (pair, accent); duration = its mount duration (2.5 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("ui/icon-morph-beat", {
  params: {"pair": "mic-check", "accent": "green", "duration": 2.5, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["pair", "accent"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "icon-morph-beat.html", p.at, vars, p.duration, p.theme, []);
  },
});
