/* ui/vector-editor: A dark design-tool app chrome with a live vector pen path, sequential anchor points, bezier handles, a selection frame, and theme-driven blue accents.
   HyperFrames registry component vector-editor-rig, run as shipped (assets/vector-editor-rig.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (tool, pathLabel); duration = its mount duration (4.5 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("ui/vector-editor", {
  params: {"tool": "pen", "pathLabel": "Logo", "duration": 4.5, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["tool", "pathLabel"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "vector-editor-rig.html", p.at, vars, p.duration, p.theme, []);
  },
});
