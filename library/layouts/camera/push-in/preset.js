/* camera/push-in: A centered headline gains focus through one slow, continuous camera push and a gentle fade out.
   HyperFrames registry component push-in, run as shipped (assets/push-in.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (text, intensity); duration = its mount duration (4 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("camera/push-in", {
  params: {"text": "Focus", "intensity": "standard", "duration": 4.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["text", "intensity"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "push-in.html", p.at, vars, p.duration, p.theme, []);
  },
});
