/* camera/pan-stations: A lateral camera move across a continuous row of labeled feature stations, with a steady dwell at each stop before the next pan.
   HyperFrames registry component pan-stations, run as shipped (assets/pan-stations.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (stationCount, labels, dwell); duration = its mount duration (4 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("camera/pan-stations", {
  params: {"stationCount": 4, "labels": "Capture,Edit,Render,Share", "dwell": 0.6, "duration": 4.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["stationCount", "labels", "dwell"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "pan-stations.html", p.at, vars, p.duration, p.theme, []);
  },
});
