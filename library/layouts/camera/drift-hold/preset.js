/* camera/drift-hold: A centered content card stays subtly alive through loop-exact rotation, scale breathing, and a slow light sweep.
   HyperFrames registry component drift-hold, run as shipped (assets/drift-hold.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (text, intensity); duration = its mount duration (4 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("camera/drift-hold", {
  params: {"text": "Always alive", "intensity": "standard", "duration": 4.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["text", "intensity"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "drift-hold.html", p.at, vars, p.duration, p.theme, []);
  },
});
