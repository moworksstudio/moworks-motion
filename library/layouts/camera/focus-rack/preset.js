/* camera/focus-rack: Focus shifts once between two cards at different apparent depths through synchronized blur, dimming, scale, and parallax.
   HyperFrames registry component focus-rack, run as shipped (assets/focus-rack.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (label_a, label_b, accent); duration = its mount duration (3.5 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("camera/focus-rack", {
  params: {"label_a": "Draft", "label_b": "Published", "accent": "blue", "duration": 3.5, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["label_a", "label_b", "accent"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "focus-rack.html", p.at, vars, p.duration, p.theme, []);
  },
});
