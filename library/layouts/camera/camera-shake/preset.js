/* camera/camera-shake: Procedural handheld, telephoto and rig camera shake for any wrapper: nine measured profiles with per-lens projection, closed-form and seek-safe
   HyperFrames registry component camera-shake, run as shipped (assets/demo.html) in an iframe over the target box, scaled from 1920 x 1080 and kept in
   step with the film (ctx.hfFrame + engine/vendor/libs/hf/hf-frame.js). duration = the block's own length (6 s). replace: [[from, to],
   ...] changes copy in the page before it runs (e.g. Vietnamese text). Generated by engine/tests/hf_blocks.py. */
AIMK.preset("camera/camera-shake", {
  params: {"shakeProfile": "handheld-normal-mild", "shakeIntensity": 1, "shakeFrequency": 1, "shakeRotation": true, "duration": 6.0, "replace": []},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["shakeProfile", "shakeIntensity", "shakeFrequency", "shakeRotation"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hfFrame(slot, "demo.html", p.at, p.duration, Object.assign({"size": [1920, 1080], "libs": {}, "urls": {}, "files": ["camera-shake.html"], "dirs": [], "imageVars": []}, { replace: p.replace, images: p.images, vars }));
  },
});
