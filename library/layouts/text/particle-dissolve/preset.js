/* text/particle-dissolve: Text assembles from a seeded particle cloud (or dissolves into it): per-particle targets sampled once from the rendered text bitmap at mount, table-driven particles, zero per-particle tweens, one onUpdate painter.
   HyperFrames registry component particle-text-dissolve, run as shipped (assets/particle-text-dissolve.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (text, direction, density, accent, exit); duration = its mount duration (4 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("text/particle-dissolve", {
  params: {"text": "Dissolve", "direction": "in", "density": "med", "accent": "green", "exit": "none", "duration": 4.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["text", "direction", "density", "accent", "exit"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "particle-text-dissolve.html", p.at, vars, p.duration, p.theme, []);
  },
});
