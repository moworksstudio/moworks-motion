/* compare/grade-split-reveal: The same picture twice, one flat and one finished, with a hard edge sweeping between them. It stops in the middle long enough to compare, then commits and the graded look takes the frame. Both looks are real HyperFrames color grading run through the WebGL shader, so the preview and the render match.
   HyperFrames registry component grade-split-reveal, run as shipped (assets/grade-split-reveal.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (look, split, edge, labels); duration = its mount duration (6 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("compare/grade-split-reveal", {
  params: {"look": "warm-cinematic", "split": 62, "edge": "hairline", "labels": "on", "duration": 6.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["look", "split", "edge", "labels"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "grade-split-reveal.html", p.at, vars, p.duration, p.theme, []);
  },
});
