/* line/separator: A one-pixel structural separator with horizontal and vertical variants plus a seek-safe progress reveal
   HyperFrames registry component separator, run as shipped (assets/demo.html) in an iframe over the target box, scaled from 1920 x 1080 and kept in
   step with the film (ctx.hfFrame + engine/vendor/libs/hf/hf-frame.js). duration = the block's own length (4 s). replace: [[from, to],
   ...] changes copy in the page before it runs (e.g. Vietnamese text). Generated by engine/tests/hf_blocks.py. */
AIMK.preset("line/separator", {
  params: {"orientation": "horizontal", "thickness": "hairline", "tone": "neutral", "duration": 4.0, "replace": []},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["orientation", "thickness", "tone"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hfFrame(slot, "demo.html", p.at, p.duration, Object.assign({"size": [1920, 1080], "libs": {}, "urls": {}, "files": ["separator.html"], "dirs": [], "imageVars": []}, { replace: p.replace, images: p.images, vars }));
  },
});
