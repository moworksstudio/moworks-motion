/* transition/paper-collage: A scrapbook patchwork of torn paper scraps, each with its own texture and tilt, flutters away in a staggered scatter to reveal the content underneath.
   HyperFrames registry component paper-collage-reveal, run as shipped (assets/paper-collage-reveal.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (panels, tone, spread); duration = its mount duration (2.6 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("transition/paper-collage", {
  params: {"panels": 6, "tone": "mixed", "spread": "outward", "duration": 2.6, "theme": {"--fg": "#1d1b16", "--surface": "#fffdf8", "--accent-2": "#b98a4e"}, "slots": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["panels", "tone", "spread"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "paper-collage-reveal.html", p.at, vars, p.duration, p.theme, [], p.slots);
  },
});
