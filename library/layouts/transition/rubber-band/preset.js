/* transition/rubber-band: An outgoing panel pulls against increasing resistance, holds at tension, then snaps past an edge with overshoot as the incoming panel settles behind it.
   HyperFrames registry component rubber-band-bumper, run as shipped (assets/rubber-band-bumper.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (direction, accent); duration = its mount duration (2.5 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("transition/rubber-band", {
  params: {"direction": "up", "accent": "green", "duration": 2.5, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["direction", "accent"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "rubber-band-bumper.html", p.at, vars, p.duration, p.theme, []);
  },
});
