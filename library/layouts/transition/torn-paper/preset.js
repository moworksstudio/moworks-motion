/* transition/torn-paper: A fibrous paper tear runs across the frame: the torn sheet shows its white paper core along the edge and lifts away on a soft shadow, leaving the next scene standing.
   HyperFrames registry component torn-paper-rip, run as shipped (assets/torn-paper-rip.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (direction, tone, roughness); duration = its mount duration (2.4 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("transition/torn-paper", {
  params: {"direction": "left-to-right", "tone": "cream", "roughness": 55, "duration": 2.4, "theme": {"--fg": "#1d1b16"}, "slots": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["direction", "tone", "roughness"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "torn-paper-rip.html", p.at, vars, p.duration, p.theme, [], p.slots);
  },
});
