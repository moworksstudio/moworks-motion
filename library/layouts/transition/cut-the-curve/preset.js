/* transition/cut-the-curve: A velocity-matched directional hard cut: the outgoing subject accelerates with power4.in, swaps at peak velocity, and the incoming subject continues in the same direction with power4.out.
   HyperFrames registry component cut-the-curve, run as shipped (assets/cut-the-curve.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (subject, direction, cutFraction, blurPx, exit); duration = its mount duration (1 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("transition/cut-the-curve", {
  params: {"subject": "cursor", "direction": "left", "cutFraction": 0.33, "blurPx": 12, "exit": "none", "duration": 1.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["subject", "direction", "cutFraction", "blurPx", "exit"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "cut-the-curve.html", p.at, vars, p.duration, p.theme, []);
  },
});
