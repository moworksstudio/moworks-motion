/* transition/chromatic-wipe: A fast slide wipe with RGB channel split on peak frames.
   HyperFrames registry component chromatic-aberration-wipe, run as shipped (assets/demo.html) in an iframe over the target box, scaled from 1920 x 1080 and kept in
   step with the film (ctx.hfFrame + engine/vendor/libs/hf/hf-frame.js). duration = the block's own length (5 s). replace: [[from, to],
   ...] changes copy in the page before it runs (e.g. Vietnamese text). Generated by engine/tests/hf_blocks.py. */
AIMK.preset("transition/chromatic-wipe", {
  params: {"direction": "left", "accent": "blue", "aberration": 1, "duration": 5.0, "replace": []},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["direction", "accent", "aberration"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hfFrame(slot, "demo.html", p.at, p.duration, Object.assign({"size": [1920, 1080], "libs": {}, "urls": {}, "files": ["chromatic-aberration-wipe.html"], "dirs": [], "imageVars": []}, { replace: p.replace, images: p.images, vars }));
  },
});
