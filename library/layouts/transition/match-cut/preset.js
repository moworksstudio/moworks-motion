/* transition/match-cut: A circle accelerates into a hard single-frame scene swap, matches the incoming circle exactly, and continues into a smaller resting pose.
   HyperFrames registry component match-cut, run as shipped (assets/match-cut.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (accent, label_a, label_b); duration = its mount duration (4 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("transition/match-cut", {
  params: {"accent": "green", "label_a": "Start", "label_b": "Done", "duration": 4.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["accent", "label_a", "label_b"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "match-cut.html", p.at, vars, p.duration, p.theme, []);
  },
});
