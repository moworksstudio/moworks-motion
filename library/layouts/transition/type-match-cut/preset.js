/* transition/type-match-cut: A headline splits vertically around an incoming panel, which grows from the negative space and takes the frame as the words exit through opposite edges.
   HyperFrames registry component type-match-cut, run as shipped (assets/type-match-cut.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (text, accent); duration = its mount duration (4 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("transition/type-match-cut", {
  params: {"text": "Meet the new editor", "accent": "green", "duration": 4.0, "theme": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["text", "accent"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "type-match-cut.html", p.at, vars, p.duration, p.theme, []);
  },
});
