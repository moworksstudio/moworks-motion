/* transition/morph-swap: Two slotted siblings stacked at one shared center: A holds, then condenses or reshapes into B on a shared 50% 50% transform origin. Condense shrink-fades A exactly as B scales up; reshape morphs the silhouette on scaleX/scaleY, never width or height tweens. Token card defaults render when a slot is left empty.
   HyperFrames registry component morph-swap, run as shipped (assets/morph-swap.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (swap_at, register, accent, exit); duration = its mount duration (3.5 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("transition/morph-swap", {
  params: {"swap_at": 1.4, "register": "condense", "accent": "green", "exit": "none", "duration": 3.5, "theme": {}, "slots": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["swap_at", "register", "accent", "exit"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "morph-swap.html", p.at, vars, p.duration, p.theme, [], p.slots);
  },
});
