/* transition/halftone-dissolve: Scene A dissolves into scene B through a growing halftone dot field: accent ink dots pop onto a fixed grid smallest-first, each opens into a window onto B, until the windows merge and B fully replaces A.
   HyperFrames registry component halftone-dissolve, run as shipped (assets/halftone-dissolve.html, through ctx.hf and engine/vendor/libs/hf/hf-mount.js:
   own ids, variables and timeline). BLOCK: the component fills the target box (its cqw / cqh are that box). Params = the component's
   variables (dot_size, direction, dissolve_at, accent, exit); duration = its mount duration (3.5 s), which sets its envelope. Generated by
   engine/tests/hf_templates.py. */
AIMK.preset("transition/halftone-dissolve", {
  params: {"dot_size": "medium", "direction": "ltr", "dissolve_at": 1.1, "accent": "green", "exit": "none", "duration": 3.5, "theme": {}, "slots": {}},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of ["dot_size", "direction", "dissolve_at", "accent", "exit"]) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hf(slot, "halftone-dissolve.html", p.at, vars, p.duration, p.theme, [], p.slots);
  },
});
