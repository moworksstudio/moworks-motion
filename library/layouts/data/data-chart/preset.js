/* data/data-chart: Animated bar + line chart with staggered reveal, NYT-style typography, and value labels
   HyperFrames registry block data-chart, run as shipped (assets/data-chart.html) in an iframe over the target box, scaled from 1920 x 1080 and kept in
   step with the film (ctx.hfFrame + engine/vendor/libs/hf/hf-frame.js). duration = the block's own length (15 s). replace: [[from, to],
   ...] changes copy in the page before it runs (e.g. Vietnamese text). Generated by engine/tests/hf_blocks.py. */
AIMK.preset("data/data-chart", {
  params: {"duration": 15.0, "replace": []},
  build(tl, els, p, ctx) {
    const vars = {}; for (const k of []) if (p[k] !== undefined) vars[k] = p[k];
    for (const slot of els) ctx.hfFrame(slot, "data-chart.html", p.at, p.duration, Object.assign({"size": [1920, 1080], "libs": {}, "urls": {}, "files": [], "dirs": [], "imageVars": []}, { replace: p.replace, images: p.images, vars }));
  },
});
